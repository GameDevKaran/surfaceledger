"""Owned deterministic synthetic boards, with truth authored before analysis."""
import json
from pathlib import Path

import cv2
import numpy as np

from .pipeline import InputError, require_opencv5


def generate(output: Path) -> dict:
    require_opencv5()
    if output.exists() and any(output.iterdir()):
        raise InputError("Fixture output directory must be new or empty.")
    output.mkdir(parents=True, exist_ok=True)
    sets = []
    for number, seed in enumerate((2417, 7919), 1):
        folder = output / f"board-{number}"
        folder.mkdir()
        random = np.random.default_rng(seed)
        # Original random textures and shapes; no third-party images or training data.
        board = random.integers(30, 220, (512, 768, 3), dtype=np.uint8)
        for _ in range(90):
            center = tuple(int(x) for x in random.integers([10, 10], [758, 502]))
            color = tuple(int(x) for x in random.integers(35, 220, 3))
            cv2.circle(board, center, int(random.integers(3, 17)), color, 2)
        images = {
            "reference.png": board,
            "left.png": board[:, :320].copy(),
            "right.png": board[:, 448:].copy(),
            "bridge.png": board[:, 256:512].copy(),
            "blurred.png": cv2.GaussianBlur(board[:, 448:], (25, 25), 6),
            "blank.png": np.full((512, 320, 3), 125, np.uint8),
            "glare.png": board[:, 448:].copy(),
        }
        images["glare.png"][128:384, 64:256] = 255
        # A second synthetic camera pose exercises projective registration, not just translation.
        board_corners = np.float32([[0, 0], [767, 0], [767, 511], [0, 511]])
        camera_corners = np.float32([[36, 24], [731, 42], [748, 476], [20, 492]])
        board_to_camera = cv2.getPerspectiveTransform(board_corners, camera_corners)
        images["perspective.png"] = cv2.warpPerspective(board, board_to_camera, (768, 512))
        for name, image in images.items():
            if not cv2.imwrite(str(folder / name), image):
                raise InputError("Unable to write fixture.")
        common = {
            "schema_version": 1,
            "evidence_kind": "synthetic_fixture",
            "planar_surface_confirmed": True,
            "reference": "reference.png",
            "width_mm": 768,
            "height_mm": 512,
            "cell_px": 64,
        }
        scenarios = {
            "gap": ["left", "right"],
            "recaptured": ["left", "right", "bridge"],
            "weak": ["left", "blurred"],
            "glare": ["left", "glare"],
            "invalid": ["blank"],
            "perspective": ["perspective"],
        }
        for scenario, captures in scenarios.items():
            manifest = {**common, "captures": [{"id": name, "file": f"{name}.png"} for name in captures]}
            (folder / f"{scenario}.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        truth = {
            "kind": "authored_synthetic_geometry",
            "seed": seed,
            "license": "MIT; generated by this repository",
            "dimensions_px": [768, 512],
            "gap_rectangle_px": [320, 0, 448, 512],
            "gap_core_grid_columns": [5, 6],
            "source_translations_px": {"left": [0, 0], "right": [448, 0], "bridge": [256, 0]},
            "glare_rectangle_board_px": [512, 128, 704, 384],
            "invalid_capture": "blank.png",
            "perspective_camera_corners_px": camera_corners.tolist(),
            "perspective_expected_board_corners_px": board_corners.tolist(),
            "known_limit": "These are crops of generated boards, not photographs or held-out camera sessions.",
        }
        (folder / "expected.json").write_text(json.dumps(truth, indent=2) + "\n", encoding="utf-8")
        sets.append(str(folder / "gap.json"))
    return {"evidence_kind": "synthetic_fixture", "capture_sets": sets}
